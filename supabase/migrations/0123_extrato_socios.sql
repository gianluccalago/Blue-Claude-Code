-- ===========================================================================
-- 0123 — EXTRATO DOS SÓCIOS (contas Seniors Care) + Demonstrativo de Caixa.
-- ---------------------------------------------------------------------------
-- Digitalização da planilha mensal do sócio-diretor (saldo inicial, entradas
-- e movimentações societárias, saídas, saldo final — SEMPRE regime de caixa).
-- Alimenta o "Demonstrativo de Caixa" em PDF (papel timbrado + assinatura de
-- Ernesto Carlos Lagomarsino Inurrieta, sócio-diretor), extraível por mês ou
-- ano na aba Obra → Caixa. ACESSO: master e direção APENAS.
-- Estrutura fiel à planilha:
--  · fc_extrato_mes: saldo inicial DECLARADO de cada mês (o sócio ajusta
--    centavos entre meses — ex.: rendimentos não lançados);
--  · fc_extrato: lançamentos com sinal (grupo 'entrada' = bloco superior,
--    receitas e movimentações societárias, pode ser negativo — dividendos;
--    grupo 'saida' = bloco inferior). Saldo final = inicial + Σ tudo
--    (caixa TOTAL: banco + aplicações — a planilha às vezes mostra só o
--    banco e o resto em "aplicação"; a soma confere ao centavo).
-- Seed: 43 meses (fev/2023 → ago/2026), 678 lançamentos, verbatim.
-- Idempotente (seed só com tabela vazia). Rode após a 0122.
-- ===========================================================================

create table if not exists public.fc_extrato_mes (
  mes            text primary key,             -- 'YYYY-MM'
  saldo_inicial  numeric not null,
  atualizado_em  timestamptz not null default now()
);

create table if not exists public.fc_extrato (
  id             uuid primary key default gen_random_uuid(),
  mes            text not null,
  ordem          int not null default 0,
  grupo          text not null check (grupo in ('entrada','saida')),
  rotulo         text not null,
  valor          numeric not null,             -- COM SINAL, como na planilha
  registrado_por text,
  criado_em      timestamptz not null default now()
);
create index if not exists idx_fc_extrato_mes on public.fc_extrato (mes, grupo, ordem);

drop trigger if exists trg_audit_fc_extrato on public.fc_extrato;
create trigger trg_audit_fc_extrato
  after insert or update or delete on public.fc_extrato
  for each row execute function public.fn_obra_audit();

alter table public.fc_extrato enable row level security;
alter table public.fc_extrato_mes enable row level security;

drop policy if exists fc_extrato_all on public.fc_extrato;
create policy fc_extrato_all on public.fc_extrato for all to authenticated
  using (public.app_perfil() in ('master','direcao'))
  with check (public.app_perfil() in ('master','direcao'));
drop policy if exists fc_extrato_mes_all on public.fc_extrato_mes;
create policy fc_extrato_mes_all on public.fc_extrato_mes for all to authenticated
  using (public.app_perfil() in ('master','direcao'))
  with check (public.app_perfil() in ('master','direcao'));

